import assert from 'node:assert/strict';
import { BookingClient, idempotencyKey, ApiError } from '../sdk/index.mjs';

// Creates synthetic development data; run only against your development instance.
const baseUrl = process.env.BOOKING_API_URL || 'http://localhost:8080';
const owner = new BookingClient({ baseUrl });
const customer = new BookingClient({ baseUrl });
const second = new BookingClient({ baseUrl });
const provider = new BookingClient({ baseUrl });
const slug = `sdk-demo-${crypto.randomUUID().slice(0, 8)}`;
const password = `Demo-${crypto.randomUUID()}`;
await owner.createWorkspace({ slug, name: 'SDK demo', email: 'owner@example.test', password });
await owner.login({ tenantSlug: slug, email: 'owner@example.test', password });
await customer.register({ tenantSlug: slug, email: 'customer@example.test', password });
await customer.loginWithCookie({ tenantSlug: slug, email: 'customer@example.test', password });
await second.register({ tenantSlug: slug, email: 'second@example.test', password });
await second.login({ tenantSlug: slug, email: 'second@example.test', password });
const coach = await owner.createProvider({ name: 'Demo coach', timeZone: 'Europe/Vilnius' });
const service = await owner.createService({ name: 'Lesson', durationMinutes: 30, cancellationHours: 24 });
await owner.assignServices(coach.id, [service.id]);
const invite = await owner.invite({ email: 'provider@example.test', role: 'PROVIDER', providerId: coach.id });
await provider.acceptInvitation({ token: invite.token, password, displayName: 'Demo coach' });
await provider.login({ tenantSlug: slug, email: 'provider@example.test', password });
const location = await owner.createLocation({ name: 'Studio', address: 'Synthetic address', timeZone: 'Europe/Vilnius' });
const room = await owner.createRoom(location.id, { name: 'Main room', capacity: 2 });
const start = new Date(Date.now() + 5 * 86400000); start.setUTCMilliseconds(0);
const at = minutes => new Date(start.getTime() + minutes * 60000).toISOString();
await provider.publishAvailability(coach.id, { startsAt: at(0), endsAt: at(180) });
const session = await provider.createSession({ providerId: coach.id, serviceId: service.id, roomId: room.id, startsAt: at(0), capacity: 2 }, idempotencyKey());
const seats = await Promise.all([customer.enrol(session.id, idempotencyKey()), second.enrol(session.id, idempotencyKey())]);
assert.equal((await customer.session(session.id)).bookedSeats, 2);
await assert.rejects(customer.enrol(session.id, idempotencyKey()), e => e instanceof ApiError && e.status === 409);
await provider.cancelSession(session.id);
assert.equal((await customer.booking(seats[0].id)).status, 'CANCELLED');
const input = { providerId: coach.id, serviceId: service.id, roomId: room.id, startsAt: at(0) };
const key = idempotencyKey();
const booking = await customer.createBooking(input, key);
await customer.reschedule(booking.id, at(30), idempotencyKey());
assert.equal((await customer.createBooking(input, key)).id, booking.id);
assert.equal((await customer.booking(booking.id)).startsAt, at(30).replace('.000Z', 'Z'));
const batch = await customer.bookBatch([60, 90].map(minutes => ({ ...input, startsAt: at(minutes) })), idempotencyKey());
assert.equal(batch.length, 2);
await provider.createBlockout(coach.id, { startsAt: at(120), endsAt: at(150) });
await assert.rejects(second.createBooking({ ...input, startsAt: at(120) }, idempotencyKey()), e => e instanceof ApiError && e.status === 409);
assert.ok((await customer.notifications()).items.length > 0);
assert.ok((await owner.bookingEvents()).items.length > 0);
for (const client of [customer, second, provider, owner]) await client.logout();
console.log(JSON.stringify({ workspace: slug, cookieAuthentication: true, providerPermissions: true, groupCapacity: true, rescheduleRetry: true, batchBooking: true, blockouts: true, notifications: true }, null, 2));
